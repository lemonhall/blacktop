/**
 * 震屏：**一个衰减的振荡，不是每帧一次的随机数。**
 *
 * 上一版是 `ctx.translate((Math.random() - .5) * S.shake, ...)`。人眼对"逐帧独立
 * 的位移"读到的不是"震了一下"，而是**这台机器在抖 / 这游戏在卡**——因为随机噪声
 * 恰恰是"卡顿"在视觉上的长相。线上那句"整个游戏给我的感觉就是卡卡的、不流畅"，
 * 有一份就是从这里领走的：一场混战里挨打是常事，`shake` 常年挂在 7~14，也就是
 * 每帧把整幅画随机挪 ±3.5~7 像素、还顺手随机拧一点角度。
 *
 * 换成**同一个幅度下的正弦**，读起来立刻变成"被撞得晃了一下"：位移是连续的，
 * 眼睛能跟上；而且它仍然是确定性的——同一个相位一定给出同一个偏移，探针可以量、
 * 测试可以钉。
 *
 * 三个分量用 1:2:3 的**整数倍频**（`phase`、`2×phase`、`3×phase`），不是随手取的
 * 频率：`phase` 每 2π 绕回一次，整数倍频在绕回点上**接得上**，不会每 120 毫秒
 * 突然跳一下——那又变成了另一种"抖"。
 */

/** 位移上限占 `amp` 的比例。`amp` 是"份量"，不是像素。 */
const DX = 0.45, DY = 0.3, ROT = 0.00035;

/** 低于这个份量就别动了：静止的画面不该有一丝无谓的抖动。 */
const DEAD = 0.05;

/**
 * 这一刻的震屏偏移。`amp` 小到看不出来时返回 `null`（调用方据此整段跳过变换——
 * 多一次 `save/restore` 也是钱）。
 */
export function shakeOffset(phase, amp) {
  if (!(amp > DEAD) || !Number.isFinite(phase)) return null;
  return {
    dx: Math.sin(phase) * amp * DX,
    dy: Math.sin(phase * 2 + 1.1) * amp * DY,
    rot: Math.sin(phase * 3 + 2.2) * amp * ROT,
  };
}
